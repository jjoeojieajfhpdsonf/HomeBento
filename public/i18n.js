"use strict";
// Texts in German and English; the browser language decides (German for de-*, else English).
// language: chosen in the settings (this device), else the browser's
const LANG = (() => {
	let pick = null;
	try {
		pick = localStorage.getItem("homebento.lang");
	} catch {
		// storage blocked
	}
	if (pick === "de" || pick === "en") return pick;
	return /^de\b/i.test(navigator.language || "") ? "de" : "en";
})();
document.documentElement.lang = LANG;
// dates and numbers: Swiss style in Switzerland (time zone or a "-CH" browser language), whatever the language
const LOCALE = (() => {
	let ch = (navigator.languages || []).some((l) => /-CH$/i.test(l));
	try {
		ch = ch || Intl.DateTimeFormat().resolvedOptions().timeZone === "Europe/Zurich";
	} catch {
		// no Intl time zone
	}
	return ch ? `${LANG}-CH` : LANG === "de" ? "de-DE" : "en-GB";
})();

